#!/usr/bin/env python3
"""Embed the recorded race weather (OpenF1 session 9912).

--extract WEATHER_JSON   writes data/monza-2025-weather.json from a downloaded
                         https://api.openf1.org/v1/weather?session_key=9912 response.
build()                  returns the generated header (called by generate_race_assets.py).
"""
import argparse, datetime as dt, hashlib, json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
SOURCE = 'https://api.openf1.org/v1/weather?session_key=9912'
FIELDS = ('air_temperature', 'track_temperature', 'humidity', 'pressure', 'wind_speed', 'wind_direction', 'rainfall')

def _origin():
    return dt.datetime.fromisoformat(json.loads((ROOT / 'data/monza-2025-provenance.json').read_text())['race_origin_utc'])

def extract(path):
    raw = Path(path).read_bytes()
    rows = json.loads(raw)
    assert rows and all(r['session_key'] == 9912 for r in rows)
    origin = _origin()
    samples = []
    for r in sorted(rows, key=lambda r: r['date']):
        race_ms = round((dt.datetime.fromisoformat(r['date']) - origin).total_seconds() * 1000)
        samples.append([race_ms] + [r[k] for k in FIELDS])
    data = {
        'source': SOURCE,
        'response_sha256': hashlib.sha256(raw).hexdigest(),
        'retrieved_utc': dt.datetime.now(dt.timezone.utc).strftime('%Y-%m-%d'),
        'note': 'Trackside weather station readings, about one per minute. race_ms is relative to the race-clock origin in monza-2025-provenance.json.',
        'units': {'air_temperature': 'degC', 'track_temperature': 'degC', 'humidity': '%', 'pressure': 'hPa',
                  'wind_speed': 'm/s', 'wind_direction': 'degrees, direction the wind blows from, clockwise from north', 'rainfall': '0 dry / 1 rain'},
        'columns': ['race_ms', *FIELDS],
        'samples': samples,
    }
    (ROOT / 'data/monza-2025-weather.json').write_text(json.dumps(data, indent=1) + '\n')

def build():
    data = json.loads((ROOT / 'data/monza-2025-weather.json').read_text())
    assert data['columns'] == ['race_ms', *FIELDS]
    samples = data['samples']
    assert all(a[0] < b[0] for a, b in zip(samples, samples[1:]))
    text = '#pragma once\n// Generated by tools/generate_weather_assets.py from data/monza-2025-weather.json.\n'
    text += f'// {data["source"]} (SHA-256 {data["response_sha256"]})\n'
    text += '#include <array>\nnamespace apex3d::cp3 {\n'
    text += 'struct WeatherSample {int raceMs;double airC,trackC,humidity,pressureHpa,windMs;int windFromDegrees;bool rain;};\n'
    text += f'inline constexpr std::array<WeatherSample,{len(samples)}> recordedWeather{{{{\n'
    for s in samples:
        text += f'    {{{s[0]}, {s[1]}, {s[2]}, {s[3]}, {s[4]}, {s[5]}, {s[6]}, {"true" if s[7] else "false"}}},\n'
    text += '}};\n}\n'
    return text

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--extract', metavar='WEATHER_JSON')
    args = parser.parse_args()
    if args.extract: extract(args.extract)
    else: print(build(), end='')
